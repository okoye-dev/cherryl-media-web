const BACKEND_URL =
  process.env.NEXT_PUBLIC_BACKEND_URL ||
  process.env.BACKEND_URL ||
  "http://localhost:8080";

export async function getLeadStory(): Promise<CanonicalArticle> {
  const all = await getAllArticles();
  const lead = all.find((a) => a.isLead);
  return lead || all[0] || CANONICAL_ARTICLES[0];
}

export async function getDispatches(): Promise<CanonicalArticle[]> {
  const all = await getAllArticles();
  return all.filter((a) => !a.isLead && a.category !== "stories-romance");
}

export async function getOpinionColumns(): Promise<CanonicalArticle[]> {
  const all = await getAllArticles();
  return all.filter(
    (a) => a.category === "stories-romance" || a.category === "business-institutions"
  );
}

export async function getAllArticles(): Promise<CanonicalArticle[]> {
  try {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 2500);

    const res = await fetch(`${BACKEND_URL}/api/articles`, {
      next: { revalidate: 30 },
      signal: controller.signal,
    });
    clearTimeout(timeout);

    if (res.ok) {
      const data = await res.json();
      if (Array.isArray(data) && data.length > 0) {
        return data as CanonicalArticle[];
      }
    }
  } catch {
    // Graceful fallback to verified canonical registry
  }
  return CANONICAL_ARTICLES;
}

export async function getArticleBySlug(slug: string): Promise<CanonicalArticle | null> {
  const normalized = slug.trim().toLowerCase();

  try {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 2500);

    const res = await fetch(`${BACKEND_URL}/api/articles/${normalized}`, {
      next: { revalidate: 30 },
      signal: controller.signal,
    });
    clearTimeout(timeout);

    if (res.ok) {
      const data = await res.json();
      if (data && data.slug) {
        return data as CanonicalArticle;
      }
    }
  } catch {
    // Fallback to local lookup
  }

  return CANONICAL_ARTICLES.find((a) => a.slug === normalized) || null;
}

export async function getAllArticleSlugs(): Promise<string[]> {
  const all = await getAllArticles();
  return all.map((a) => a.slug);
}

export async function getArticlesByCategory(category: string): Promise<CanonicalArticle[]> {
  const all = await getAllArticles();
  const filtered = all.filter((a) => a.category === category);
  if (filtered.length > 0) return filtered;
  return CANONICAL_ARTICLES.filter((a) => a.category === category);
}
